-- NPT-risk scoring and diesel forecast over the synthetic snapshot.
-- Predicts P(NPT event in the next 7 days) per rig and reports
-- out-of-time holdout metrics; nothing is seeded as a prediction.
USE DATABASE IDENTIFIER($DEMO_DB);
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE VIEW ML.NPT_FEATURES AS
SELECT r.ENTITY_ID, r.EVENT_DATE, t.CATEGORY, t.AGE_YEARS,
       r.SPP_BAR, r.HOOKLOAD_PCT,
       AVG(r.SPP_BAR) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS SPP_7D,
       SUM(r.NPT_EVENTS) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS NPT_EVENTS_30D,
       IFF(SUM(r.NPT_EVENTS) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) > 0,
           'NPT', 'OK') AS LABEL,
       COUNT(*) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS
FROM RAW.RIG_DAILY r JOIN RAW.RIGS t ON t.ID = r.ENTITY_ID
-- Supply-base standby events are not rig-driven, so they are excluded from training.
WHERE r.ROOT_CAUSE NOT IN ('Monsoon weather standby', 'Supply vessel delay') OR r.NPT_EVENTS = 0;

-- Time-based split: train on older labelled days, hold out the most recent 14 labelled days.
CREATE VIEW ML.NPT_TRAIN AS
SELECT CATEGORY, AGE_YEARS, SPP_BAR, HOOKLOAD_PCT, SPP_7D, NPT_EVENTS_30D, LABEL
FROM ML.NPT_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE < DATEADD('day', -21, CURRENT_DATE());

CREATE VIEW ML.NPT_HOLDOUT AS
SELECT ENTITY_ID, EVENT_DATE, CATEGORY, AGE_YEARS, SPP_BAR, HOOKLOAD_PCT, SPP_7D, NPT_EVENTS_30D, LABEL
FROM ML.NPT_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE >= DATEADD('day', -21, CURRENT_DATE());

CREATE SNOWFLAKE.ML.CLASSIFICATION ML.NPT_RISK_MODEL(
  INPUT_DATA => TABLE(ML.NPT_TRAIN),
  TARGET_COLNAME => 'LABEL'
);

-- Out-of-time holdout: precision/recall at 0.5 versus the base rate.
CREATE TABLE ML.NPT_RISK_HOLDOUT_METRICS AS
WITH scored AS (
  SELECT LABEL, ML.NPT_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'AGE_YEARS', AGE_YEARS, 'SPP_BAR', SPP_BAR,
           'HOOKLOAD_PCT', HOOKLOAD_PCT, 'SPP_7D', SPP_7D, 'NPT_EVENTS_30D', NPT_EVENTS_30D)):probability:NPT::FLOAT AS P
  FROM ML.NPT_HOLDOUT
)
SELECT COUNT(*) AS N,
       AVG(IFF(LABEL = 'NPT', 1, 0)) AS BASE_RATE,
       SUM(IFF(P >= 0.5 AND LABEL = 'NPT', 1, 0)) / NULLIF(SUM(IFF(P >= 0.5, 1, 0)), 0) AS PRECISION_AT_50,
       SUM(IFF(P >= 0.5 AND LABEL = 'NPT', 1, 0)) / NULLIF(SUM(IFF(LABEL = 'NPT', 1, 0)), 0) AS RECALL_AT_50,
       CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM scored;

-- Latest-day score per rig (label unknown, so excluded from features).
CREATE TABLE ML.NPT_RISK_SCORES AS
WITH latest AS (
  SELECT * FROM ML.NPT_FEATURES
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_DATE DESC) = 1
), scored AS (
  SELECT ENTITY_ID, EVENT_DATE,
         ML.NPT_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'AGE_YEARS', AGE_YEARS, 'SPP_BAR', SPP_BAR,
           'HOOKLOAD_PCT', HOOKLOAD_PCT, 'SPP_7D', SPP_7D, 'NPT_EVENTS_30D', NPT_EVENTS_30D)) AS P
  FROM latest
)
SELECT ENTITY_ID, EVENT_DATE AS SCORED_AS_OF,
       ROUND(P:probability:NPT::FLOAT, 4) AS NPT_PROB_7D,
       CASE WHEN P:probability:NPT::FLOAT >= 0.5 THEN 'High'
            WHEN P:probability:NPT::FLOAT >= 0.25 THEN 'Medium' ELSE 'Low' END AS RISK_BAND,
       CURRENT_TIMESTAMP() AS SCORED_AT
FROM scored;

-- Fleet-wide daily diesel forecast (14 days, m3) from the daily series.
CREATE VIEW ML.DAILY_FUEL AS
SELECT EVENT_DATE::TIMESTAMP_NTZ AS TS, SUM(FUEL_M3)::FLOAT AS FUEL_M3
FROM RAW.RIG_DAILY GROUP BY EVENT_DATE;

CREATE SNOWFLAKE.ML.FORECAST ML.FUEL_FORECAST_MODEL(
  INPUT_DATA => TABLE(ML.DAILY_FUEL),
  TIMESTAMP_COLNAME => 'TS',
  TARGET_COLNAME => 'FUEL_M3'
);

CREATE TABLE ML.FUEL_FORECAST AS
SELECT TS::DATE AS FORECAST_DATE, ROUND(FORECAST) AS FUEL_M3,
       ROUND(GREATEST(0, LOWER_BOUND)) AS LOWER_BOUND, ROUND(UPPER_BOUND) AS UPPER_BOUND
FROM TABLE(ML.FUEL_FORECAST_MODEL!FORECAST(FORECASTING_PERIODS => 14));
