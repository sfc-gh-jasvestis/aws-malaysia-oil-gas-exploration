-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT rig.ID AS ENTITY_ID, rig.NAME AS ENTITY_NAME,
       rig.REGION, rig.CATEGORY, rig.STATUS,
       COUNT(*) AS EVENT_COUNT, SUM(o.NPT_EVENTS) AS NPT_EVENTS,
       SUM(o.PRODUCTIVE_HOURS) AS PRODUCTIVE_HOURS, SUM(o.PLANNED_HOURS) AS PLANNED_HOURS,
       SUM(o.NPT_HOURS) AS NPT_HOURS,
       SUM(o.BOP_TEST_DUE) AS BOP_TEST_DUE, SUM(o.BOP_TEST_DONE) AS BOP_TEST_DONE,
       SUM(o.METRES_DRILLED) AS METRES_DRILLED, SUM(o.FUEL_M3) AS FUEL_M3,
       SUM(o.CHECKS_IN_SPEC) AS CHECKS_IN_SPEC, SUM(o.MUD_CHECKS) AS MUD_CHECKS,
       SUM(o.KICKS) AS KICKS,
       100.0 * SUM(o.CHECKS_IN_SPEC) / NULLIF(SUM(o.MUD_CHECKS), 0) AS IN_SPEC_PCT,
       1000.0 * SUM(o.FUEL_M3) / NULLIF(SUM(o.METRES_DRILLED), 0) AS FUEL_L_PER_M,
       100.0 * SUM(o.PRODUCTIVE_HOURS) / NULLIF(SUM(o.PLANNED_HOURS), 0) AS PRODUCTIVE_TIME_PCT,
       100.0 * SUM(o.BOP_TEST_DONE) / NULLIF(SUM(o.BOP_TEST_DUE), 0) AS BOP_TEST_COMPLETION_PCT,
       MAX(o.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.RIG_DAILY o
JOIN RAW.RIGS rig ON rig.ID = o.ENTITY_ID
GROUP BY rig.ID, rig.NAME, rig.REGION, rig.CATEGORY, rig.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(CHECKS_IN_SPEC) AS CHECKS_IN_SPEC, SUM(MUD_CHECKS) AS MUD_CHECKS,
       SUM(METRES_DRILLED) AS METRES_DRILLED, SUM(FUEL_M3) AS FUEL_M3,
       SUM(KICKS) AS KICKS, SUM(NPT_EVENTS) AS NPT_EVENTS,
       100.0 * SUM(CHECKS_IN_SPEC) / NULLIF(SUM(MUD_CHECKS), 0) AS IN_SPEC_PCT,
       1000.0 * SUM(FUEL_M3) / NULLIF(SUM(METRES_DRILLED), 0) AS FUEL_L_PER_M
FROM RAW.RIG_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.NPT_CAUSES
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT ROOT_CAUSE, SUM(NPT_EVENTS) AS NPT_EVENTS,
       SUM(NPT_HOURS) AS NPT_HOURS,
       SUM(MUD_CHECKS) - SUM(CHECKS_IN_SPEC) AS CHECKS_OFF_SPEC
FROM RAW.RIG_DAILY
WHERE NPT_EVENTS > 0
GROUP BY ROOT_CAUSE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(CHECKS_IN_SPEC) AS CHECKS_IN_SPEC, SUM(MUD_CHECKS) AS MUD_CHECKS,
         SUM(METRES_DRILLED) AS METRES_DRILLED, SUM(FUEL_M3) AS FUEL_M3,
         SUM(KICKS) AS KICKS, SUM(NPT_EVENTS) AS NPT_EVENTS,
         SUM(PRODUCTIVE_HOURS) AS PRODUCTIVE_HOURS, SUM(PLANNED_HOURS) AS PLANNED_HOURS,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.RIG_DAILY
), rigs AS (SELECT COUNT(*) AS RIG_COUNT FROM RAW.RIGS),
wells AS (
  SELECT 100.0 * SUM(LEAST(DRILLED_DEPTH_M, PLANNED_DEPTH_M)) / NULLIF(SUM(PLANNED_DEPTH_M), 0) AS DEPTH_PROGRESS_PCT
  FROM RAW.WELL_PROGRESS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Mud Checks Within Spec' AS TITLE,
         100.0 * CHECKS_IN_SPEC / NULLIF(MUD_CHECKS, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'NPT Events', NPT_EVENTS, '' FROM observations
  UNION ALL SELECT 3, 'Diesel Intensity', 1000.0 * FUEL_M3 / NULLIF(METRES_DRILLED, 0), ' L/m' FROM observations
  UNION ALL SELECT 4, 'Diesel Used (m3)', FUEL_M3, '' FROM observations
  UNION ALL SELECT 5, 'Productive Time', 100.0 * PRODUCTIVE_HOURS / NULLIF(PLANNED_HOURS, 0), '%' FROM observations
  UNION ALL SELECT 6, 'Rigs Monitored', RIG_COUNT, '' FROM rigs
  UNION ALL SELECT 7, 'Current-Well Depth Progress', DEPTH_PROGRESS_PCT, '%' FROM wells
  UNION ALL SELECT 8, 'Well-Control Kicks', KICKS, '' FROM observations
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '999,990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.NPT_CAUSES SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
